    function renderLawResults() {
        const results = document.getElementById('lawResults');
        const stats = document.getElementById('lawStats');
        const input = document.getElementById('lawSearchInput');
        if (!results) return;

        const query = (input?.value || '').trim().toLowerCase();
        let totalCount = 0;
        let html = '';

        lawActiveCodes.forEach(code => {
            const codeData = legislationData[code];
            if (!codeData) return;

            const filtered = codeData.items.filter(item => {
                if (!query) return true;
                const haystack = (
                    (item.title || '') + ' ' +
                    (item.content || '') + ' ' +
                    (item.punishment || '') + ' ' +
                    (item.note || '')
                ).toLowerCase();
                return haystack.includes(query);
            });

            filtered.forEach(item => {
                                totalCount++;
                const title = query ? highlightText(escapeHtml(item.title), query) : escapeHtml(item.title);
                const content = query ? highlightText(escapeHtml(item.content), query) : escapeHtml(item.content);
                const punishment = item.punishment ? (query ? highlightText(escapeHtml(item.punishment), query) : escapeHtml(item.punishment)) : '';
                const note = item.note ? (query ? highlightText(escapeHtml(item.note), query) : escapeHtml(item.note)) : '';

                html += `<article class="law-card">
                    <div class="law-card-header">
                        <span class="law-card-code">${codeData.name}</span>
                        <span class="law-card-title">${title}</span>
                    </div>
                    <div class="law-card-text">${content}</div>
                    ${punishment ? `<div class="law-card-punishment"><i class="fas fa-gavel"></i><div><strong>Наказание:</strong> ${punishment}</div></div>` : ''}
                    ${note ? `<div class="law-card-note"><strong>Примечание:</strong> ${note}</div>` : ''}
                </article>`;
            });
        });

        if (totalCount === 0) {
            results.innerHTML = `<div class="law-empty">
                <i class="fas fa-search"></i>
                <p>Ничего не найдено</p>
                <small>${query ? `По запросу "${escapeHtml(query)}"` : 'В выбранных кодексах пока нет статей'}</small>
            </div>`;
        } else {
            results.innerHTML = html;
        }

        if (stats) {
            stats.innerHTML = `Найдено статей: <strong>${totalCount}</strong>${query ? ` по запросу «${escapeHtml(query)}»` : ''}`;
        }
    }

    function highlightText(text, query) {
        if (!query || !text) return text || '';
        const safeQuery = query.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        const regex = new RegExp(`(${safeQuery})`, 'gi');
        return text.replace(regex, '<span class="law-highlight">$1</span>');
    }

    function escapeHtml(str) {
        if (!str) return '';
        return String(str)
            .replace(/&/g, '&amp;')
            .replace(/</g, '&lt;')
            .replace(/>/g, '&gt;');
    }
